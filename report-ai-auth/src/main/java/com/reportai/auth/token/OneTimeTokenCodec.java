package com.reportai.auth.token;

import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.HexFormat;

/** Generates and validates opaque, URL-safe credentials without persisting their raw form. */
public final class OneTimeTokenCodec {
    public static final int TOKEN_BYTES = 32;
    private static final Base64.Encoder ENCODER = Base64.getUrlEncoder().withoutPadding();
    private static final Base64.Decoder DECODER = Base64.getUrlDecoder();

    private OneTimeTokenCodec() {
    }

    public static String generate(SecureRandom random) {
        if (random == null) {
            throw new NullPointerException("random");
        }
        byte[] bytes = new byte[TOKEN_BYTES];
        random.nextBytes(bytes);
        return ENCODER.encodeToString(bytes);
    }

    /** Returns a lowercase SHA-256 digest of a token generated by this codec. */
    public static String sha256(String rawToken) {
        byte[] tokenBytes = decode(rawToken);
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(tokenBytes));
        } catch (NoSuchAlgorithmException impossible) {
            throw new IllegalStateException("SHA-256 is unavailable", impossible);
        }
    }

    private static byte[] decode(String rawToken) {
        if (rawToken == null || rawToken.length() != 43) {
            throw new IllegalArgumentException("token is invalid");
        }
        try {
            byte[] decoded = DECODER.decode(rawToken);
            if (decoded.length != TOKEN_BYTES || !ENCODER.encodeToString(decoded).equals(rawToken)) {
                throw new IllegalArgumentException("token is invalid");
            }
            return decoded;
        } catch (IllegalArgumentException invalid) {
            throw new IllegalArgumentException("token is invalid", invalid);
        }
    }
}
